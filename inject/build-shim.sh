set -euo pipefail
cd "$(dirname "$0")/.."

SDK=.deps/native/ps5-payload-sdk/bin
CC=$SDK/prospero-clang
OBJCOPY=$SDK/prospero-objcopy
out=build/inject
mkdir -p "$out"

bash docker/run.sh "$CC" \
    -fPIC -ffreestanding -fno-stack-protector -fomit-frame-pointer \
    -fno-jump-tables -fno-builtin -O2 -Wall \
    -nostdlib -nostartfiles \
    -Wl,--build-id=none -Wl,-no-pie -Wl,-T,inject/shim.ld \
    -o "$out/mic_shim.elf" inject/mic_shim.c

bash docker/run.sh objcopy -O binary \
    --only-section=.text "$out/mic_shim.elf" "$out/mic_shim.bin"

size=$(wc -c < "$out/mic_shim.bin")
echo "mic_shim.bin: $size bytes"

{
    echo "/* Generated by inject/build-shim.sh - do not edit. */"
    echo "#ifndef PSCORD_MIC_SHIM_BLOB_H"
    echo "#define PSCORD_MIC_SHIM_BLOB_H"
    echo "static const unsigned char mic_shim_blob[] = {"
    xxd -i < "$out/mic_shim.bin"
    echo "};"
    echo "static const unsigned mic_shim_blob_len = ${size}u;"
    echo "#endif"
} > "$out/mic_shim_blob.h"

echo "wrote $out/mic_shim_blob.h"

# PartyDaemon PCM ring player (background Discord voice).
bash docker/run.sh "$CC" \
    -fPIC -ffreestanding -fno-stack-protector -fomit-frame-pointer \
    -fno-jump-tables -fno-builtin -O2 -Wall \
    -nostdlib -nostartfiles \
    -Wl,--build-id=none -Wl,-no-pie -Wl,-T,inject/shim.ld \
    -o "$out/pump_shim.elf" inject/pump_shim.c

bash docker/run.sh objcopy -O binary \
    --only-section=.text "$out/pump_shim.elf" "$out/pump_shim.bin"

psize=$(wc -c < "$out/pump_shim.bin")
echo "pump_shim.bin: $psize bytes"

{
    echo "/* Generated by inject/build-shim.sh - do not edit. */"
    echo "#ifndef PSCORD_PUMP_SHIM_BLOB_H"
    echo "#define PSCORD_PUMP_SHIM_BLOB_H"
    echo "static const unsigned char pump_shim_blob[] = {"
    xxd -i < "$out/pump_shim.bin"
    echo "};"
    echo "static const unsigned pump_shim_blob_len = ${psize}u;"
    echo "#endif"
} > "$out/pump_shim_blob.h"

echo "wrote $out/pump_shim_blob.h"
